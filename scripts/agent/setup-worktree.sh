#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# setup-worktree.sh <branch|slug> [base-branch]
#
# Creates an isolated sibling git worktree + branch for one feature, allocates
# a unique port block, and writes the worktree's .env.local.
#
# Worktree path:  ../<primary-basename>-wt-<slug>
#   e.g. /home/felipe/workfolder/imoveis-wt-add-login
#
# Prefer scripts/agent/setup-workspace.sh — it chooses solo branch vs worktree.
#
# Prints the worktree path on the LAST line (machine-readable).
# ---------------------------------------------------------------------------
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "$HERE/lib.sh"

[ $# -ge 1 ] || die "usage: setup-worktree.sh <branch|slug> [base-branch]"

INPUT="$1"
if echo "$INPUT" | grep -q '/'; then
  BRANCH="$INPUT"
  validate_conventional_branch "$BRANCH" || die "branch '$BRANCH' violates Conventional Branch v1.1.0"
else
  SLUG="$(sanitize_proj "$INPUT")"
  [ -n "$SLUG" ] || die "empty/invalid feature slug"
  DETECTED_TYPE=""
  while IFS='|' read -ra _types; do
    for _t in "${_types[@]}"; do
      if [[ "$SLUG" == "$_t-"* ]]; then
        DETECTED_TYPE="$_t"
        SLUG="${SLUG#$_t-}"
        break 2
      fi
    done
  done <<< "$VALID_BRANCH_TYPES"
  if [ -n "$DETECTED_TYPE" ]; then
    BRANCH="$DETECTED_TYPE/$SLUG"
  else
    BRANCH="feat/$SLUG"
  fi
fi

parse_branch "$BRANCH"
SLUG="$BRANCH_DESC"
BASE_BRANCH="${2:-main}"
PROJ="$(sanitize_proj "$BRANCH")"
WORKTREE="$(worktree_path_for_slug "$SLUG")"

log "Preparing isolated worktree for '$BRANCH' at $WORKTREE"

if git -C "$PRIMARY_ROOT" remote get-url origin >/dev/null 2>&1; then
  git -C "$PRIMARY_ROOT" fetch origin --quiet || warn "git fetch failed; using local $BASE_BRANCH"
  git -C "$PRIMARY_ROOT" rev-parse --verify "origin/$BASE_BRANCH" >/dev/null 2>&1 && BASE_REF="origin/$BASE_BRANCH" || BASE_REF="$BASE_BRANCH"
else
  BASE_REF="$BASE_BRANCH"
fi

if [ -d "$WORKTREE" ]; then
  warn "worktree already exists at $WORKTREE — reusing it"
else
  mkdir -p "$WORKTREE_PARENT"
  if git -C "$PRIMARY_ROOT" rev-parse --verify "$BRANCH" >/dev/null 2>&1; then
    git -C "$PRIMARY_ROOT" worktree add "$WORKTREE" "$BRANCH"
  else
    git -C "$PRIMARY_ROOT" worktree add -b "$BRANCH" "$WORKTREE" "$BASE_REF"
  fi
  ok "worktree created at $WORKTREE (branch $BRANCH from $BASE_REF)"
fi

# --- Allocate ports under the registry lock ---------------------------------
registry_lock
trap registry_unlock EXIT

if [ -f "$REGISTRY_FILE" ] && grep -qP "^$BRANCH\t" "$REGISTRY_FILE" 2>/dev/null; then
  PG="$(registry_get "$BRANCH" 3)"; RD="$(registry_get "$BRANCH" 4)"
  API="$(registry_get "$BRANCH" 5)"; FE="$(registry_get "$BRANCH" 6)"
  ok "reusing registered ports pg=$PG redis=$RD api=$API fe=$FE"
else
  BASE="$(alloc_port_block "$BRANCH")"
  PG=$((BASE + 0)); RD=$((BASE + 1)); API=$((BASE + 2)); FE=$((BASE + 3))
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$BRANCH" "$PROJ" "$PG" "$RD" "$API" "$FE" "$WORKTREE" >> "$REGISTRY_FILE"
  ok "allocated ports pg=$PG redis=$RD api=$API fe=$FE"
fi

# PLAYWRIGHT_PORT is separate from Compose FRONTEND_PORT (ephemeral Vite for E2E).
# Allocate under the same ports lock so parallel setups do not all land on 5177.
PW_PREFERRED=$((5177 + (FE % 100)))
if [ "$PW_PREFERRED" -lt 5177 ] || [ "$PW_PREFERRED" -gt 5299 ]; then
  PW_PREFERRED=5177
fi
# Reuse existing .env.local PLAYWRIGHT_PORT when re-running setup on same worktree.
PW=""
if [ -f "$WORKTREE/.env.local" ]; then
  PW="$(awk -F= '/^PLAYWRIGHT_PORT=/{print $2; exit}' "$WORKTREE/.env.local" 2>/dev/null || true)"
fi
if [ -z "$PW" ] || ! port_free "$PW"; then
  PW="$(alloc_playwright_port "$PW_PREFERRED")"
fi
ok "allocated PLAYWRIGHT_PORT=$PW (Compose FE=$FE stays separate)"

registry_unlock
trap - EXIT

cat > "$WORKTREE/.env.local" <<EOF
# Auto-generated by setup-worktree.sh — do NOT commit, do NOT hand-edit ports.
COMPOSE_PROJECT_NAME=$PROJ
POSTGRES_PORT=$PG
REDIS_PORT=$RD
API_PORT=$API
FRONTEND_PORT=$FE
PLAYWRIGHT_PORT=$PW
EOF
ok ".env.local written"

# validate.sh prefers $REPO_ROOT/.venv; worktrees have none — link primary's
# so host pytest does not fall back to system python (missing pgvector, etc.).
if [ -x "$PRIMARY_ROOT/.venv/bin/python" ] && [ ! -e "$WORKTREE/.venv" ]; then
  ln -sfn "$PRIMARY_ROOT/.venv" "$WORKTREE/.venv" \
    && ok "symlinked .venv from primary" \
    || warn "could not symlink .venv (optional — create one or pip install -r requirements.txt)"
fi

# Single local harness: symlink primary .cursor (do NOT copy — teardown would lose edits).
# Legacy: older setups copied .cursor/ into the worktree. Replace a real directory
# safely: only rm -rf when the path is exactly $WORKTREE/.cursor, is a directory,
# and is NOT already a symlink — then ln -sfn to primary.
if [ -d "$PRIMARY_ROOT/.cursor" ]; then
  _cursor_dest="$WORKTREE/.cursor"
  if [ -L "$_cursor_dest" ]; then
    ln -sfn "$PRIMARY_ROOT/.cursor" "$_cursor_dest" \
      && ok "symlinked .cursor/ harness from primary" \
      || warn "could not refresh .cursor/ symlink (optional)"
  elif [ -d "$_cursor_dest" ] && [ ! -L "$_cursor_dest" ]; then
    # Path-guard: only rm -rf a directory that is exactly $WORKTREE/.cursor.
    case "$_cursor_dest" in
      "$WORKTREE/.cursor")
        rm -rf -- "$_cursor_dest"
        ln -sfn "$PRIMARY_ROOT/.cursor" "$_cursor_dest" \
          && ok "replaced legacy .cursor/ directory with symlink from primary" \
          || warn "could not replace legacy .cursor/ (optional)"
        ;;
      *)
        warn "refusing to remove unexpected .cursor path: $_cursor_dest"
        ;;
    esac
  elif [ ! -e "$_cursor_dest" ]; then
    ln -sfn "$PRIMARY_ROOT/.cursor" "$_cursor_dest" \
      && ok "symlinked .cursor/ harness from primary" \
      || warn "could not symlink .cursor/ (optional)"
  else
    warn "unexpected non-directory at $_cursor_dest — skip .cursor symlink"
  fi
fi

# Sync agent scripts from primary ONLY when primary has local (uncommitted)
# harness edits — otherwise a busy primary on an old feature branch can
# overwrite a worktree that was correctly created from origin/main.
if [ -d "$PRIMARY_ROOT/scripts/agent" ] \
  && [ -n "$(git -C "$PRIMARY_ROOT" status --porcelain -- scripts/agent 2>/dev/null)" ]; then
  mkdir -p "$WORKTREE/scripts/agent"
  cp -a "$PRIMARY_ROOT/scripts/agent/." "$WORKTREE/scripts/agent/" 2>/dev/null \
    && ok "synced dirty scripts/agent/ from primary" \
    || warn "could not sync scripts/agent/ (optional)"
fi

echo ""
echo "  MODE=parallel"
echo "  BRANCH=$BRANCH"
echo "  Workspace ready. Next steps:"
echo "    1. move_agent_to_root → $WORKTREE   (or: cd \"$WORKTREE\")"
echo "    2. bash scripts/agent/run-services.sh"
echo ""
# Last line = worktree path (machine-readable for the caller).
echo "$WORKTREE"
